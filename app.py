@app.route("/", methods=["GET", "POST"])
def home():

    if not session.get("logged_in"):

        return redirect(
            url_for("login")
        )


    prediction = None

    fruit = None

    freshness = None

    confidence = None

    recommendation = None

    image_path = None

    error = None


    # ========================================================
    # CURRENT USER RECORDS
    # ========================================================

    all_records = load_records()

    current_email = session.get(
        "user_email",
        ""
    )


    user_records = [

        record

        for record in all_records

        if record.get(
            "email",
            ""
        ) == current_email

    ]


    # ========================================================
    # INITIAL STATISTICS
    # ========================================================

    (
        total_inspections,
        fresh_count,
        rotten_count,
        ripe_count,
        unripe_count,
        overripe_count
    ) = calculate_statistics(
        user_records
    )


    # ========================================================
    # IMAGE UPLOAD
    # ========================================================

    if request.method == "POST":

        if "image" not in request.files:

            error = "Please select an image."

        else:

            file = request.files["image"]


            if file.filename == "":

                error = "Please select an image."

            else:

                try:

                    # ------------------------------------------------
                    # SECURE FILENAME
                    # ------------------------------------------------

                    original_name = secure_filename(
                        file.filename
                    )


                    # ------------------------------------------------
                    # UNIQUE FILENAME
                    # ------------------------------------------------

                    timestamp = datetime.now().strftime(
                        "%Y%m%d_%H%M%S_%f"
                    )


                    filename = (
                        timestamp
                        + "_"
                        + original_name
                    )


                    save_path = os.path.join(
                        app.config["UPLOAD_FOLDER"],
                        filename
                    )


                    # ------------------------------------------------
                    # SAVE IMAGE
                    # ------------------------------------------------

                    file.save(save_path)


                    # ------------------------------------------------
                    # LOAD IMAGE
                    # ------------------------------------------------

                    image = load_img(
                        save_path,
                        target_size=(224, 224)
                    )


                    image_array = img_to_array(
                        image
                    )


                    image_array = np.expand_dims(
                        image_array,
                        axis=0
                    )


                    # ------------------------------------------------
                    # PREDICTION
                    # ------------------------------------------------

                    predictions = model.predict(
                        image_array,
                        verbose=0
                    )


                    predicted_index = int(
                        np.argmax(
                            predictions[0]
                        )
                    )


                    predicted_class = CLASS_NAMES[
                        predicted_index
                    ]


                    confidence = round(
                        float(
                            predictions[0][
                                predicted_index
                            ] * 100
                        ),
                        2
                    )


                    # ------------------------------------------------
                    # FORMAT RESULT
                    # ------------------------------------------------

                    fruit, freshness = format_prediction(
                        predicted_class
                    )


                    prediction = predicted_class


                    recommendation = RECOMMENDATIONS.get(
                        predicted_class,
                        "Please inspect the food carefully before consumption."
                    )


                    # ------------------------------------------------
                    # PATH USED BY HTML
                    # ------------------------------------------------

                    image_path = "/" + save_path.replace(
                        "\\",
                        "/"
                    )


                    # =================================================
                    # SAVE RECORD
                    # =================================================

                    records = load_records()


                    records.append({

                        "user":
                            session.get(
                                "user_name",
                                "User"
                            ),

                        "email":
                            session.get(
                                "user_email",
                                ""
                            ),

                        "prediction":
                            prediction,

                        "fruit":
                            fruit,

                        "freshness":
                            freshness,

                        "confidence":
                            confidence,

                        "image":
                            image_path,

                        "date":
                            datetime.now().strftime(
                                "%d %b %Y, %I:%M %p"
                            )

                    })


                    save_records(records)


                    # =================================================
                    # UPDATE STATISTICS
                    # =================================================

                    all_records = records


                    user_records = [

                        record

                        for record in all_records

                        if record.get(
                            "email",
                            ""
                        ) == current_email

                    ]


                    (
                        total_inspections,
                        fresh_count,
                        rotten_count,
                        ripe_count,
                        unripe_count,
                        overripe_count
                    ) = calculate_statistics(
                        user_records
                    )


                except Exception as e:

                    error = (
                        "Unable to process the image: "
                        + str(e)
                    )


    # ========================================================
    # RENDER DASHBOARD
    # ========================================================

    return render_template(

        "index.html",

        prediction=prediction,

        fruit=fruit,

        freshness=freshness,

        confidence=confidence,

        recommendation=recommendation,

        image_path=image_path,

        error=error,

        user_name=session.get(
            "user_name",
            "User"
        ),

        user_role=session.get(
            "user_role",
            "Food Inspector"
        ),

        total_inspections=total_inspections,

        fresh_count=fresh_count,

        rotten_count=rotten_count,

        ripe_count=ripe_count,

        unripe_count=unripe_count,

        overripe_count=overripe_count

    )


