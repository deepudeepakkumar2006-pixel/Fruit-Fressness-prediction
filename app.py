# FORMAT PREDICTION
# ============================================================

def format_prediction(predicted_class):

    if "_" in predicted_class:

        fruit, freshness = predicted_class.split("_", 1)

        fruit = fruit.capitalize()

        freshness = freshness.capitalize()

    else:

        # Banana-only classes
        # ripe, unripe, overripe, rotten

        fruit = "Banana"

        freshness = predicted_class.capitalize()

    return fruit, freshness


# ============================================================
# STATISTICS FUNCTION
# ============================================================

def calculate_statistics(user_records):

    total_inspections = len(user_records)

    fresh_count = 0

    rotten_count = 0

    ripe_count = 0

    unripe_count = 0

    overripe_count = 0


    for record in user_records:

        prediction = str(
            record.get("prediction", "")
        ).lower()

        freshness = str(
            record.get("freshness", "")
        ).lower()


        # ----------------------------------------------------
        # FRESH
        # ----------------------------------------------------

        if freshness == "fresh" or prediction.endswith("_fresh"):

            fresh_count += 1


        # ----------------------------------------------------
        # ROTTEN
        # ----------------------------------------------------

        if freshness == "rotten" or prediction.endswith("_rotten"):

            rotten_count += 1

        elif prediction == "rotten":

            rotten_count += 1


        # ----------------------------------------------------
        # BANANA RIPE
        # ----------------------------------------------------

        if prediction == "ripe":

            ripe_count += 1


        # ----------------------------------------------------
        # BANANA UNRIPE
        # ----------------------------------------------------

        if prediction == "unripe":

            unripe_count += 1


        # ----------------------------------------------------
        # BANANA OVERRIPE
        # ----------------------------------------------------

        if prediction == "overripe":

            overripe_count += 1


    return (
        total_inspections,
        fresh_count,
        rotten_count,
        ripe_count,
        unripe_count,
        overripe_count
    )


